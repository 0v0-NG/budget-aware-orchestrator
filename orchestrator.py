# orchestrator.py
import sqlite3
from dag_validator import validate_plan, get_execution_order
from mckp_router import solve_mckp_routing
from api_client import execute_prompt

def run_simulation():
    print("\n--- Budget-Aware Orchestrator: Simulation Mode ---")
    
    # 1. Connect to the database
    conn = sqlite3.connect('orchestrator.db')
    cursor = conn.cursor()
    
    # 2. Create a new Run
    budget_cap = 0.0050
    cursor.execute(
        "INSERT INTO RUN (task, budget_level, cap, status) VALUES (?, ?, ?, ?)",
        ("Analyze financial report", "Standard", budget_cap, "IN_PROGRESS")
    )
    run_id = cursor.lastrowid
    print(f"[*] Started Run ID: {run_id} with Budget Cap: ${budget_cap}")
    
    # 3. Define a mock workflow (Normally generated by a Planner AI)
    subtasks = [
        {'id': 1, 'task_type': 'extraction', 'description': 'Extract key metrics from text', 'est_tokens_in': 500, 'est_tokens_out': 200, 'depends_on': []},
        {'id': 2, 'task_type': 'reasoning', 'description': 'Calculate trends based on metrics', 'est_tokens_in': 800, 'est_tokens_out': 400, 'depends_on': [1]}
    ]
    
    # 4. Validate and sort the DAG
    is_valid, msg = validate_plan(subtasks)
    if not is_valid:
        print(f"[!] DAG Error: {msg}")
        return
        
    exec_order = get_execution_order(subtasks)
    print(f"[*] DAG Validated. Execution Order: {exec_order}")
    
    # 5. Route tasks using MCKP
    mock_models = [
        {'model_id': 1, 'identifier': 'llama-3.1-8b-instant', 'provider': 'groq', 'input_price': 0.0001, 'output_price': 0.0002, 'quality_scores': {'extraction': 0.8, 'reasoning': 0.6}},
        {'model_id': 2, 'identifier': 'llama-3.3-70b-versatile', 'provider': 'groq', 'input_price': 0.0008, 'output_price': 0.0012, 'quality_scores': {'extraction': 0.9, 'reasoning': 0.95}}
    ]
    
    feasible, plan, est_cost, quality, msg = solve_mckp_routing(subtasks, mock_models, budget_cap)
    if not feasible:
        print(f"[!] Routing Error: {msg}")
        cursor.execute("UPDATE RUN SET status = 'FAILED_BUDGET' WHERE run_id = ?", (run_id,))
        conn.commit()
        return
        
    print(f"[*] Routing Successful. Total Est Cost: ${est_cost} | Quality: {quality}")
    
    # 6. Execute tasks and write to Ledger
    for task_id in exec_order:
        task_def = next(t for t in subtasks if t['id'] == task_id)
        assignment = plan[task_id]
        model_id = assignment['model_id']
        model_name = assignment['identifier']
        provider = next(m['provider'] for m in mock_models if m['model_id'] == model_id)
        
        print(f"\n[>] Executing Task {task_id}: '{task_def['description']}'")
        print(f"    Assigned to: {model_name} (Cost: ${assignment['est_cost']})")
        
        response = execute_prompt(provider, model_name, task_def['description'])
        print(f"    Response: {response}") 
        
        cursor.execute('''
            INSERT INTO LEDGER 
            (run_id, subtask_id, model_id, attempt, est_cost, input_price, output_price, decision, reason)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            run_id, task_id, model_id, 1, assignment['est_cost'], 
            0.0, 0.0, "SUCCESS", "Task completed via simulation"
        ))
        print("    [+] Ledger entry recorded in database.")
        
    # 7. Complete the Run
    cursor.execute("UPDATE RUN SET status = 'COMPLETED' WHERE run_id = ?", (run_id,))
    conn.commit()
    conn.close()
    print("\n[*] Simulation Complete. All records permanently saved to SQLite.")

if __name__ == "__main__":
    run_simulation()